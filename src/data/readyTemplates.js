// Helper search & filter functions
export function getTemplateById(id) {
  return READY_TEMPLATES.find((t) => t.id === id) || READY_TEMPLATES[0];
}

export function filterReadyTemplates({
  category = "all",
  style = "all",
  language = "all",
  colorTheme = "all",
  search = "",
}) {
  return READY_TEMPLATES.filter((tpl) => {
    // Category match
    if (category !== "all" && tpl.category !== category) {
      return false;
    }
    // Style match
    if (style !== "all" && tpl.styleKey !== style) {
      return false;
    }
    // Language match
    if (language !== "all" && tpl.language !== language) {
      return false;
    }
    // Color theme match
    if (colorTheme !== "all") {
      const colorDef = TEMPLATE_COLORS.find((c) => c.id === colorTheme);
      if (colorDef && colorDef.matchPalettes) {
        const matchesPalette = colorDef.matchPalettes.some((pKey) => {
          const pal = COLOR_PALETTES[pKey];
          return (
            pal &&
            (tpl.design?.palette === pal ||
              tpl.design?.palette?.name === pal.name ||
              tpl.design?.palette?.cardBg === pal.cardBg)
          );
        });
        if (!matchesPalette) {
          return false;
        }
      }
    }
    // Search match
    if (search.trim()) {
      const q = search.toLowerCase();
      const matchTitle = tpl.title.toLowerCase().includes(q);
      const matchBangla = tpl.banglaTitle.includes(q);
      const matchBride = tpl.design.content.brideName?.toLowerCase().includes(q) || tpl.design.content.brideName?.includes(q);
      const matchGroom = tpl.design.content.groomName?.toLowerCase().includes(q) || tpl.design.content.groomName?.includes(q);
      const matchVenue = tpl.design.content.venue?.toLowerCase().includes(q) || tpl.design.content.venue?.includes(q);
      const matchCity = tpl.design.content.city?.toLowerCase().includes(q) || tpl.design.content.city?.includes(q);
      const matchBadge = tpl.badge.toLowerCase().includes(q);
      return matchTitle || matchBangla || matchBride || matchGroom || matchVenue || matchCity || matchBadge;
    }
    return true;
  });
}
