// Helper to assemble full design object
function makeDesign({
  template,
  language = "en",
  culturalStyle = "classic",
  palette,
  typography = { headingFont: "Playfair Display", bodyFont: "DM Sans" },
  decorations = {},
  content,
}) {
  return {
    template,
    language,
    culturalStyle,
    palette,
    typography,
    decorations: {
      hasFloralCorners: true,
      hasGoldBorder: true,
      hasWaxSeal: true,
      hasInnerFrame: true,
      monogram: content.brideName?.[0] && content.groomName?.[0] ? `${content.brideName[0]}&${content.groomName[0]}` : "W",
      ...decorations,
    },
    content,
  };
}

